from __future__ import annotations

import hashlib
import os
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Protocol

from sqlalchemy.orm import Session

from app.infra.media.ffprobe import MediaProbeResult
from app.models import ArchiveJob, ArchiveSourceSnapshot, AuditEvent, LocalAsset, SourceRecording


class ArchiveValidationError(RuntimeError):
    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


class MediaProbe(Protocol):
    def probe(self, path: Path) -> MediaProbeResult: ...


@dataclass(frozen=True)
class VerificationPolicy:
    min_size_bytes: int = 1024
    duration_tolerance_ms: int = 5000
    size_tolerance_bytes: int = 4096


@dataclass(frozen=True)
class RetryPolicy:
    max_attempts: int = 3
    base_delay_seconds: float = 1.0
    max_delay_seconds: float = 30.0

    def delay_for_attempt(self, attempt: int) -> float | None:
        if attempt < 1 or attempt >= self.max_attempts:
            return None
        return min(self.base_delay_seconds * (2 ** (attempt - 1)), self.max_delay_seconds)


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _read_prefix(path: Path, size: int = 512) -> bytes:
    with path.open("rb") as handle:
        return handle.read(size)


def reject_error_payload(path: Path) -> None:
    prefix = _read_prefix(path).lstrip().lower()
    if prefix.startswith(b"<?xml") or prefix.startswith(b"<xml") or prefix.startswith(b"<html") or b"<html" in prefix[:128]:
        raise ArchiveValidationError("DOWNLOAD_ERROR_PAYLOAD")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def quarantine_partial_file(
    session: Session,
    *,
    path: Path,
    storage_root: Path,
    job_id: str,
    actor: str = "archive-worker",
) -> Path | None:
    """Preserve a stale/invalid partial payload in a scoped quarantine path."""
    if not path.exists():
        return None
    root = storage_root.resolve(strict=False)
    resolved = path.resolve(strict=False)
    if not resolved.is_relative_to(root):
        raise ArchiveValidationError("ARCHIVE_PATH_UNSAFE")
    quarantine_dir = root / ".quarantine"
    quarantine_dir.mkdir(parents=True, exist_ok=True)
    target = quarantine_dir / f"{job_id}.{path.name}.{uuid.uuid4().hex}.partial"
    os.replace(path, target)
    session.add(
        AuditEvent(
            id=f"audit-partial-quarantined-{job_id}-{uuid.uuid4().hex}",
            event_type="archive_partial_quarantined",
            entity_type="archive_job",
            entity_id=job_id,
            actor=actor,
            payload_redacted=None,
        )
    )
    return target


def verify_part(
    part_path: Path,
    *,
    expected_duration_ms: int,
    expected_size_bytes: int | None = None,
    probe: MediaProbe,
    policy: VerificationPolicy = VerificationPolicy(),
) -> tuple[str, MediaProbeResult, int]:
    if not part_path.exists() or not part_path.is_file():
        raise ArchiveValidationError("DOWNLOAD_MISSING")
    size = part_path.stat().st_size
    if size < policy.min_size_bytes:
        raise ArchiveValidationError("DOWNLOAD_TOO_SMALL")
    reject_error_payload(part_path)
    try:
        media = probe.probe(part_path)
    except Exception as exc:
        if isinstance(exc, ArchiveValidationError):
            raise
        raise ArchiveValidationError("MEDIA_PROBE_FAILED") from exc
    if not media.has_video:
        raise ArchiveValidationError("VIDEO_STREAM_MISSING")
    # Hikvision's search index can report a duration different from the
    # complete MPEG payload returned by the matching playback URI.  The URI's
    # size is a stronger identity signal here: it is generated by the NVR for
    # that segment and the response has a stable 40-byte transport overhead.
    # Do not accept a duration discrepancy from size alone unless ffprobe has
    # still found a video stream, and keep the old strict path when the NVR did
    # not provide a size.
    size_matched = expected_size_bytes is not None and abs(size - expected_size_bytes) <= policy.size_tolerance_bytes
    if media.duration_ms <= 0:
        if not size_matched:
            raise ArchiveValidationError("MEDIA_DURATION_MISSING")
    else:
        duration_delta_ms = abs(media.duration_ms - expected_duration_ms)
        if duration_delta_ms > policy.duration_tolerance_ms and not size_matched:
            raise ArchiveValidationError("MEDIA_DURATION_MISMATCH")
    digest = sha256_file(part_path)
    return digest, media, size


def finalize_archive_job(
    session: Session,
    *,
    job: ArchiveJob,
    source: SourceRecording,
    storage_volume_id: str,
    relative_path: str,
    part_path: Path,
    final_path: Path,
    storage_root: Path | None = None,
    probe: MediaProbe,
    asset_id: str,
    verification_duration_ms: int | None = None,
    verification_size_bytes: int | None = None,
    actor: str = "system",
    policy: VerificationPolicy = VerificationPolicy(),
) -> LocalAsset:
    """Verify, atomically promote and only then establish completed archive fact."""
    job.state = "verifying"
    session.flush()
    if storage_root is not None:
        root = storage_root.resolve(strict=False)
        if not final_path.resolve(strict=False).is_relative_to(root) or not part_path.resolve(strict=False).is_relative_to(root):
            raise ArchiveValidationError("ARCHIVE_PATH_UNSAFE")
    recovered_promoted_file = final_path.exists()
    try:
        # os.replace may have completed before the following database commit
        # was durable. A valid file at the deterministic source path is
        # verified and re-adopted; it is never deleted or downloaded again.
        candidate_path = final_path if recovered_promoted_file else part_path
        digest, media, size = verify_part(
            candidate_path,
            expected_duration_ms=verification_duration_ms if verification_duration_ms is not None else source.duration_ms,
            expected_size_bytes=verification_size_bytes if verification_size_bytes is not None else source.source_size_if_known,
            probe=probe,
            policy=policy,
        )
        final_path.parent.mkdir(parents=True, exist_ok=True)
        if not recovered_promoted_file:
            if final_path.exists():
                raise ArchiveValidationError("FINAL_PATH_EXISTS")
            os.replace(part_path, final_path)
        now = _utcnow()
        snapshot = ArchiveSourceSnapshot(
            id=f"snapshot-{asset_id}",
            source_recording_id=source.id,
            nvr_id=source.nvr_id,
            track_id=source.track_id,
            source_start=source.source_start,
            source_end=source.source_end,
            duration_ms=source.duration_ms,
            locator_fingerprint=source.locator_fingerprint,
            source_size_if_known=source.source_size_if_known,
            created_at=now,
        )
        session.add(snapshot)
        asset = LocalAsset(
            id=asset_id,
            source_recording_id=source.id,
            archive_source_snapshot_id=snapshot.id,
            storage_volume_id=storage_volume_id,
            relative_path=relative_path,
            size_bytes=size,
            sha256=digest,
            container=media.container,
            video_codec=media.video_codec,
            audio_codec=media.audio_codec,
            width=media.width,
            height=media.height,
            media_duration_ms=media.duration_ms,
            verification_state="verified",
            verified_at=now,
            lifecycle_state="present",
            archived_at=now,
        )
        session.add(asset)
        session.flush()
        job.state = "completed"
        job.completed_at = now
        session.add(
            AuditEvent(
                id=f"audit-{asset_id}",
                event_type="archive_verified",
                entity_type="local_asset",
                entity_id=asset.id,
                actor=actor,
                payload_redacted=None,
            )
        )
        if recovered_promoted_file:
            session.add(
                AuditEvent(
                    id=f"audit-orphan-recovered-{asset_id}",
                    event_type="archive_orphan_recovered",
                    entity_type="local_asset",
                    entity_id=asset.id,
                    actor=actor,
                    payload_redacted=None,
                )
            )
        session.flush()
        return asset
    except ArchiveValidationError as exc:
        job.state = "failed"
        job.error_code = exc.code
        if recovered_promoted_file:
            quarantine_error = None
            try:
                quarantine_dir = final_path.parent / ".quarantine"
                quarantine_dir.mkdir(parents=True, exist_ok=True)
                quarantine_path = quarantine_dir / f"{final_path.name}.{uuid.uuid4().hex}.invalid"
                os.replace(final_path, quarantine_path)
                job.error_code = "ORPHAN_FINAL_QUARANTINED"
                session.add(
                    AuditEvent(
                        id=f"audit-orphan-quarantined-{job.id}-{uuid.uuid4().hex}",
                        event_type="archive_orphan_quarantined",
                        entity_type="archive_job",
                        entity_id=job.id,
                        actor=actor,
                        payload_redacted=None,
                    )
                )
            except OSError:
                quarantine_error = "ORPHAN_FINAL_QUARANTINE_FAILED"
            if quarantine_error:
                job.error_code = quarantine_error
        session.flush()
        raise ArchiveValidationError(job.error_code) from exc
